#!/bin/sh
# Канонический запуск сессии-бота Beer Log (@beer_log_bot).
# Держим флаги здесь, чтобы не вспоминать их руками.
#
# Модель: базовая сессия на Sonnet. Пробовали Haiku ради лимитов (план «модель-тиринг»),
# но Haiku не тянет надёжный вызов MCP-инструментов (звал reply как «скилл») и следование
# мульти-шаговому скиллу (cat>/tmp, сырой curl). Для личного чат-бота объём токенов крохотный
# (лимиты били булк-ингесты с пачкой субагентов, не бот), поэтому база = Sonnet — надёжнее.
# Спец-эскалация субагентом больше не нужна: база сама тянет vision/reasoning. opus не используем.
#
# Канал — форкнутый плагин с вкладками (telegram@tg-tabs). Флаг dev-channels скрытый
# (не в `claude --help`), но рабочий — именно так бот и поднимается.
#
# ВАЖНО: модель задаётся ТОЛЬКО здесь, на запуске. НЕ клади "model" в
# .claude/settings.local.json репо — иначе она прилетит и на dev-сессию разработки.

# Стартуем сессию из корня репо (откуда бы скрипт ни вызвали — zellij/любая панель),
# чтобы дефолтный проект = Beer Log. Per-message tab-router всё равно делает cd <root>.
REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO" || exit 1

# --settings: пермишены ТОЛЬКО для бота (scripts/bot-settings.json) — авто-разрешают
# скрипты бота без промптов (некому подтверждать в zellij), не трогая dev-сессии репо.
exec claude --model claude-sonnet-4-6 \
  --settings "$REPO/scripts/bot-settings.json" \
  --dangerously-load-development-channels plugin:telegram@tg-tabs "$@"
